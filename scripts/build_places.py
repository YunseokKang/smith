"""Build src/smith/places_kr.txt, the place names a restaurant question may name (FR-55), from two public files.

Sources (free, no login; download them by hand and pass the paths; both are refreshed about once a year):
  --dong      국토교통부_전국 법정동 CSV (https://www.data.go.kr/data/15063424/fileData.do, "다운로드"; UTF-8 with
              BOM; columns 법정동코드, 시도명, 시군구명, 읍면동명, 리명, 순번, 생성일자).
  --stations  전체_도시철도역사정보 XLSX (철도산업정보센터, https://data.kric.go.kr/rips/M_01_01/detail.do?id=32,
              "다운로드"; data.go.kr 15013205 links there; the national urban and metropolitan railway stations,
              column 역사명). Korail's intercity-only stations are not in it; their towns are, as 시·군·읍·면.

The output holds names only (no codes, coordinates or addresses): "<kind>\t<name>" lines, kind one of station
(the name without 역), dong (읍·면·동, "성수동1가" kept as "성수동"), district (구·군), city (시). Run:
  .\\.venv\\Scripts\\python.exe scripts\\build_places.py --dong <csv> --stations <xlsx> --as-of 2026-06-30
"""
import argparse
import csv
import re
import zipfile
from pathlib import Path
from xml.etree import ElementTree

OUT = Path(__file__).resolve().parents[1] / "src" / "smith" / "places_kr.txt"
_NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
_NAME = re.compile(r"^[0-9A-Za-z가-힣]+$")


def dong_names(path: Path) -> set[tuple[str, str]]:
    found = set()
    with path.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            if (row.get("리명") or "").strip():
                continue
            for part in _districts((row.get("시군구명") or "").strip()):
                found.add(("city" if part.endswith("시") else "district", part))
            dong = re.sub(r"\d+가$", "", (row.get("읍면동명") or "").strip())
            if dong:
                found.add(("dong", dong))
    return {(kind, name) for kind, name in found if _NAME.match(name) and len(name) >= 2}


def _districts(name: str) -> list[str]:
    """"성남시분당구" -> ["성남시", "분당구"]; "종로구" -> ["종로구"]."""
    match = re.fullmatch(r"(\S+?시)(\S+구)", name)
    return list(match.groups()) if match else ([name] if name else [])


def station_names(path: Path) -> set[tuple[str, str]]:
    rows = _xlsx_rows(path)
    column = rows[0].index("역사명")
    found = set()
    for row in rows[1:]:
        raw = row[column].strip() if column < len(row) else ""
        # "총신대입구(이수)" names one station twice; some operators write "서울역", others "서울".
        for part in re.split(r"[()]", raw):
            part = part.strip()
            stem = part[:-1] if part.endswith("역") and len(part) > 2 else part
            if _NAME.match(stem) and len(stem) >= 2:
                found.add(("station", stem))
    return found


def _xlsx_rows(path: Path) -> list[list[str]]:
    """The first sheet's cells as text (standard library only: shared strings and inline strings)."""
    with zipfile.ZipFile(path) as book:
        shared = []
        if "xl/sharedStrings.xml" in book.namelist():
            for item in ElementTree.fromstring(book.read("xl/sharedStrings.xml")).iter(f"{_NS}si"):
                shared.append("".join(t.text or "" for t in item.iter(f"{_NS}t")))
        sheet = ElementTree.fromstring(book.read("xl/worksheets/sheet1.xml"))
    rows = []
    for row in sheet.iter(f"{_NS}row"):
        cells = []
        for cell in row.iter(f"{_NS}c"):
            value = cell.find(f"{_NS}v")
            if cell.get("t") == "s" and value is not None:
                cells.append(shared[int(value.text or 0)])
            elif cell.get("t") == "inlineStr":
                cells.append("".join(t.text or "" for t in cell.iter(f"{_NS}t")))
            else:
                cells.append(value.text or "" if value is not None else "")
        rows.append(cells)
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dong", type=Path, required=True)
    parser.add_argument("--stations", type=Path, required=True)
    parser.add_argument("--as-of", required=True, help="the sources' reference date, written into the header")
    args = parser.parse_args()
    names = sorted(dong_names(args.dong) | station_names(args.stations))
    header = [f"# Korean place names for restaurant questions (FR-55), as of {args.as_of}. Generated by",
              "# scripts/build_places.py from 국토교통부_전국 법정동 (data.go.kr 15063424) and 전체_도시철도역사정보",
              "# (data.kric.go.kr file data 32). Do not edit by hand. kind<TAB>name; a station without 역."]
    OUT.write_text("\n".join(header + [f"{kind}\t{name}" for kind, name in names]) + "\n", encoding="utf-8")
    counts = {kind: sum(1 for k, _ in names if k == kind) for kind in ("station", "dong", "district", "city")}
    print(f"{OUT}: {counts}")


if __name__ == "__main__":
    main()
